def clear_ecosystem_objects():
    """Helper function to clear existing ecosystem objects before re-running
    Preserves: IFC elements (river geometry), cameras, lights
    Removes: Ecosystem monitoring objects (booms, bars, platforms, text)
    """
    collection_names = [
        "KLANG_RIVER_ECOSYSTEM",
        "KLANG_INFRASTRUCTURE",
        "STORM_SIMULATION",
        "RIVER_ECOSYSTEM_MODEL",
        "BOOM_STATION_01",
        "TEST_RIVER_MONITOR",
        "RIVER_TEST",
        "KLANG_RIVER_DEBUG",
    ]

    zone_patterns = ["ZONE_", "BOOM_", "_upstream", "_midstream", "_downstream",
                    "TEST_BOOM", "FALLBACK_BOOM", "EMERGENCY_BOOM", "_UPSTREAM", "_MIDSTREAM", "_DOWNSTREAM"]

    removed_collections = 0
    removed_objects = 0

    # Remove predefined collections
    for name in collection_names:
        if name in bpy.data.collections:
            collection = bpy.data.collections[name]
            for obj in list(collection.objects):
                # Skip IFC elements (they have 'ifc_definition_id' property)
                if 'ifc_definition_id' not in obj:
                    bpy.data.objects.remove(obj, do_unlink=True)
                    removed_objects += 1
            # Remove collection if empty
            if len(collection.objects) == 0:
                bpy.data.collections.remove(collection)
                removed_collections += 1

    # Remove zone/boom pattern collections
    for col_name in list(bpy.data.collections.keys()):
        if any(pattern in col_name for pattern in zone_patterns):
            collection = bpy.data.collections[col_name]
            for obj in list(collection.objects):
                # Skip IFC elements
                if 'ifc_definition_id' not in obj:
                    bpy.data.objects.remove(obj, do_unlink=True)
                    removed_objects += 1
            # Remove collection if empty
            if len(collection.objects) == 0:
                bpy.data.collections.remove(collection)
                removed_collections += 1

    return removed_collections, removed_objects


