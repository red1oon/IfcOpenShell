class RiverEcosystemLogger:
    """Logger that writes to both console and file"""

    def __init__(self, operator_name):
        self.operator_name = operator_name
        self.step = 0

        # Setup log file (single persistent file that updates)
        log_dir = Path.home() / "Documents" / "bonsai" / "consolelogs"
        log_dir.mkdir(parents=True, exist_ok=True)

        # Use single log file instead of timestamped
        self.log_file = log_dir / "river_ecosystem_latest.txt"

        # Clear previous log and write header
        header = f"""
{'='*70}
RIVER ECOSYSTEM MODEL - {operator_name}
{'='*70}
Timestamp: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}
Log File: {self.log_file}
{'='*70}
"""
        # Overwrite file with header
        with open(self.log_file, 'w') as f:
            f.write(header + '\n')
        print(header)

    def _write(self, message):
        """Write to file"""
        try:
            with open(self.log_file, 'a') as f:
                f.write(message + '\n')
        except Exception as e:
            print(f"Warning: Could not write to log file: {e}")

    def log(self, message, error=False):
        """Log message to both console and file"""
        self.step += 1
        prefix = "❌" if error else "→"
        formatted = f"{self.step:3d}. {prefix} {message}"

        # Write to both console and file
        print(formatted)
        self._write(formatted)

        return formatted

    def section(self, title):
        """Log a section header"""
        line = f"\n{'-'*70}"
        header = f"{title}"
        formatted = f"{line}\n{header}\n{line}"

        print(formatted)
        self._write(formatted)

    def summary(self, success, message):
        """Log final summary"""
        symbol = "✅" if success else "❌"
        summary = f"""
{'='*70}
{symbol} {message}
{'='*70}
Log saved to: {self.log_file}
"""
        print(summary)
        self._write(summary)


