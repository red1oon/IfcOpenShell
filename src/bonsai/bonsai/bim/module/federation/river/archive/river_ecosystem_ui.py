            import traceback
            tb_str = traceback.format_exc()
            logger.log("TRACEBACK:")
            logger._write(tb_str)
            print(tb_str)
            logger.summary(False, f"FAILED - Exception: {str(e)}")
            self.report({'ERROR'}, f"Failed: {str(e)}")
            return {'CANCELLED'}


